"""Exports Brindle Isle's layout for Unity from our Unreal level script (Unreal/Tools/build_brindle_greybox.py).

The script is run as-is against a recording stand-in for the Unreal Python API (unreal_recorder.py), so Unity gets
exactly the same island: every greybox shape, kit piece, wind line, light and marker, converted to Unity axes.
  Unreal: X north, Y east, Z up (cm, here metres).   Unity: x east, y up, z north (metres).
  position (X, Y, Z) -> (Y, Z, X); rotation (pitch, yaw, roll) -> euler (-pitch, yaw, -roll); scale (sx, sy, sz) -> (sy, sz, sx)

  python Unity/Tools/layout/export_brindle_layout.py   (from the repository root; writes Assets/Art/Brindle/BrindleLayout.json)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SCRIPT = os.path.join(REPO, "Unreal", "Tools", "build_brindle_greybox.py")
OUT = os.path.join(REPO, "Unity", "LastSkyfarer", "Assets", "Art", "Brindle", "BrindleLayout.json")

sys.modules.pop("unreal", None)
import importlib.util
spec = importlib.util.spec_from_file_location("unreal", os.path.join(HERE, "unreal_recorder.py"))
unreal = importlib.util.module_from_spec(spec)
sys.modules["unreal"] = unreal
spec.loader.exec_module(unreal)
exec(compile(open(SCRIPT, encoding="utf-8").read(), SCRIPT, "exec"), {"__name__": "__main__"})


def P(p): return {"x": round(p[1], 4), "y": round(p[2], 4), "z": round(p[0], 4)}
def R(r): return {"x": round(-r["pitch"], 4), "y": round(r["yaw"], 4), "z": round(-r["roll"], 4)}
def S(s): return {"x": round(s[1], 4), "y": round(s[2], 4), "z": round(s[0], 4)}


items = []
for a in unreal.RECORD:
    cls, props = a["class"], a.get("props", {})
    o = {"Name": a.get("label", cls), "Folder": a.get("folder", ""), "Kind": "", "Mesh": a.get("mesh") or "", "Material": a.get("material") or "", "Pos": P(a["loc"]),
         "Euler": R(a["rot"]), "Scale": S(a["scale"]), "Hidden": a["hidden"], "Collider": a["collision"], "Climbable": "Climbable" in a["tags"],
         "Spin": 0.0, "Cull": a.get("cull", 0.0), "Shadow": a.get("shadow", True), "Tags": [t for t in a["tags"] if t != "Climbable"],
         "Points": [], "WindType": "", "Strength": 0.0, "Radius": 0.0, "StartsHidden": False, "Id": "", "Quest": "", "Objective": ""}
    if cls in ("StaticMeshActor", "LSSpinningMesh"):
        o["Kind"] = "kit" if o["Mesh"].startswith("SM_") else "shape"
        o["Spin"] = float(props.get("speed", 0.0)) if cls == "LSSpinningMesh" else 0.0
        if o["Kind"] == "kit":
            o["Collider"] = False
    elif cls == "WindVolume":
        o.update(Kind="wind", WindType=str(props.get("wind_type", "")).title(), Strength=float(props.get("strength", 0)),
                 Radius=float(props.get("radius", 0)) / 100.0, StartsHidden=bool(props.get("starts_hidden", False)),
                 Points=[P(p) for p in a.get("points", [])])
    elif cls == "PointLight":
        o["Kind"] = "lamp"
    elif cls == "PlayerStart":
        o["Kind"] = "start"
    elif cls == "LSMapMarkerActor":
        o.update(Kind="marker_" + str(props.get("kind", "")).lower(), Id=str(props.get("location_id", "")),
                 Quest=str(props.get("quest_id", "")), Objective=str(props.get("objective_id", "")))
    else:
        continue  # story actors come from Interactions.json; sky, fog and sound are set up by the Unity level
    items.append(o)

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump({"Note": "Generated by Unity/Tools/layout/export_brindle_layout.py from Unreal/Tools/build_brindle_greybox.py. Do not edit by hand.",
               "Items": items}, f, indent=1)
from collections import Counter
print("LS_LAYOUT", len(items), dict(Counter(i["Kind"] for i in items)), "->", OUT)
